/** Разбитое яйцо: нижняя скорлупа с зубчатым краем и отлетевшая верхушка */
export const BrokenEgg = ({ x, y }: { x: number; y: number }) => {
  const bottom = [
    `M${x - 16} ${y + 2}`,
    `L${x - 11} ${y - 5} L${x - 6} ${y + 1} L${x - 1} ${y - 6} L${x + 4} ${y} L${x + 9} ${y - 5} L${x + 15} ${y + 2}`,
    `C${x + 13} ${y + 13} ${x - 14} ${y + 13} ${x - 16} ${y + 2} Z`,
  ].join(' ');
  const top = [
    `M${x - 26} ${y - 8}`,
    `C${x - 26} ${y - 22} ${x - 12} ${y - 26} ${x - 6} ${y - 18}`,
    `L${x - 10} ${y - 14} L${x - 14} ${y - 18} L${x - 18} ${y - 10} Z`,
  ].join(' ');

  return (
    <>
      <path d={bottom} />
      <path d={top} />
    </>
  );
};
